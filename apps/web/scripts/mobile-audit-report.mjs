#!/usr/bin/env node
// Builds docs/mobile-audit.md from the audit runs:
//   docs/mobile-audit/before/findings/*.json   (MOBILE_AUDIT=before ...)
//   docs/mobile-audit/after/findings/*.json    (MOBILE_AUDIT=after ...)
// An issue is "fixed" if it was found before and is absent after. Anything still
// present must have an explanation in docs/mobile-audit/explanations.json
// ({ "<route>|<kind>|<where>": "why it stays" }), otherwise it is listed as OPEN.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');
const DIR = path.join(ROOT, 'docs/mobile-audit');

function load(phase) {
  const dir = path.join(DIR, phase, 'findings');
  const map = new Map(); // "route|kind|where" -> { devices:Set, themes:Set, detail }
  if (!existsSync(dir)) return map;
  for (const file of readdirSync(dir).filter((f) => f.endsWith('.json'))) {
    const [device, theme, route] = file.replace(/\.json$/, '').split('__');
    for (const f of JSON.parse(readFileSync(path.join(dir, file), 'utf8'))) {
      // "(×12)" differs per device and theme; the issue is the same one
      const where = f.where.replace(/ \(×\d+\)$/, ' (×many)');
      const key = `${route}|${f.kind}|${where}`;
      const e = map.get(key) ?? { route, kind: f.kind, where, devices: new Set(), themes: new Set(), detail: f.detail };
      e.devices.add(device);
      e.themes.add(theme);
      map.set(key, e);
    }
  }
  return map;
}

const before = load('before');
const after = load('after');
const explanationsPath = path.join(DIR, 'explanations.json');
const explanations = existsSync(explanationsPath) ? JSON.parse(readFileSync(explanationsPath, 'utf8')) : {};
const hasAfter = after.size > 0 || existsSync(path.join(DIR, 'after', 'findings'));

const KIND = {
  'horizontal-scroll': 'sideways scroll',
  offscreen: 'cut off at the screen edge',
  'small-target': 'tap target under 44×44px',
  'small-chinese': 'Chinese text under 20px',
  'small-input': 'input under 16px (iOS zooms in)',
};

const rows = [...before.values()].sort((a, b) => a.route.localeCompare(b.route) || a.kind.localeCompare(b.kind));
const status = (e) => {
  const key = `${e.route}|${e.kind}|${e.where}`;
  if (!hasAfter) return 'to do';
  if (!after.has(key)) return 'fixed';
  return explanations[key] ? `kept — ${explanations[key]}` : 'OPEN';
};

const counts = { fixed: 0, kept: 0, open: 0, todo: 0 };
for (const e of rows) {
  const s = status(e);
  if (s === 'fixed') counts.fixed++;
  else if (s.startsWith('kept')) counts.kept++;
  else if (s === 'OPEN') counts.open++;
  else counts.todo++;
}
const newAfter = [...after.values()].filter((e) => !before.has(`${e.route}|${e.kind}|${e.where}`));

const lines = [];
lines.push('# Mobile audit (phase 11)', '');
lines.push(
  'Generated by `apps/web/scripts/mobile-audit-report.mjs` from the Playwright audit (`apps/web/e2e/mobile/audit.spec.ts`).',
  'Screenshots: `docs/mobile-audit/before/` and `docs/mobile-audit/after/` (every route, light and dark, per device).',
  '',
  '## Scope',
  '',
  '- **Targets:** Safari and Chrome on newer iPhones. Chrome on iOS runs on the same WebKit engine as Safari, so one engine covers both. Devices: iPhone 13 (390px wide) and iPhone 15 Pro Max (430px wide). Android and small-phone layouts are out of scope by decision.',
  '- **Engine:** the audit runs in Playwright WebKit (the engine Safari uses), not Chromium pretending to be a phone. It is the Linux WPE build, so it matches Safari’s layout engine but not iOS’s fonts, safe-area insets, on-screen keyboard or the Add to Home Screen flow — those need a real iPhone (see “Manual checks”).',
  '- **Checks per screen:** page scrolls sideways; anything cut off at the screen edge; tap targets under 44×44px; Chinese text under 20px; text fields under 16px.',
  '- **Not in this app (so not audited):** the brief mentions a word browser, metrics page, settings page and in-app pinyin/zhuyin keyboards. They do not exist; the closest are Progress (metrics), the header controls (settings) and plain typed answers in Cloze.',
  '',
);
lines.push('## Result', '');
if (!hasAfter) {
  lines.push(`${rows.length} issues found before any fix (${new Set(rows.map((r) => r.route)).size} screens affected). Fixes not run yet.`, '');
} else {
  lines.push(
    `${rows.length} issues found before the fixes: **${counts.fixed} fixed**, ${counts.kept} kept with a reason, **${counts.open} open**.` +
      (newAfter.length ? ` ${newAfter.length} new issue(s) appeared after the changes (listed at the end).` : ''),
    '',
  );
}
lines.push('## Issues by screen', '');
let current = '';
for (const e of rows) {
  if (e.route !== current) {
    current = e.route;
    lines.push(`### ${current}`, '', '| Issue | Where | Seen on | Status |', '| --- | --- | --- | --- |');
  }
  const seen = `${[...e.devices].sort().join(', ')} · ${[...e.themes].sort().join('/')}`;
  lines.push(`| ${KIND[e.kind] ?? e.kind} (${e.detail}) | ${e.where.replace(/\|/g, '\\|')} | ${seen} | ${status(e)} |`);
  const next = rows[rows.indexOf(e) + 1];
  if (!next || next.route !== current) lines.push('');
}
if (newAfter.length) {
  lines.push('## New issues after the changes', '', '| Screen | Issue | Where |', '| --- | --- | --- |');
  for (const e of newAfter) lines.push(`| ${e.route} | ${KIND[e.kind] ?? e.kind} (${e.detail}) | ${e.where.replace(/\|/g, '\\|')} |`);
  lines.push('');
}
const manual = path.join(DIR, 'manual-notes.md');
if (existsSync(manual)) lines.push(readFileSync(manual, 'utf8').trim(), '');
writeFileSync(path.join(ROOT, 'docs/mobile-audit.md'), lines.join('\n'));
console.log(`wrote docs/mobile-audit.md — ${rows.length} issues before; fixed ${counts.fixed}, kept ${counts.kept}, open ${counts.open}`);
