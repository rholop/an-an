// Phase 48 Part D.2: the distractor audit. Builds the Review "Pick the Mandarin" set for every
// TOCFL N1–L1 word and every textbook word, with a fixed seed and a beginner's known words, and
// checks the owner rule: no odd one out, every option close to the answer, and (over all words) at
// most 5% with fewer than 3 options. Pure over the lexicon and table it is given.
import {
  axesBetween,
  charSimilarity,
  ConfusableIndex,
  levelIndex,
  oddOneOutReason,
  type DistractorTable,
  type Level,
  type Word,
} from '@anan/core';

export const AUDIT_SEED = 'phase-48-audit';
/** The beginner fixture: an A1 learner (TOCFL L1) who knows N1–L1 and book 1; options up to L2. */
export const AUDIT_LEARNER_LEVEL: Level = 'L1';
export const AUDIT_LEVEL_CAP: Level = 'L2';
export const MAX_SHORT_SHARE = 0.05;

export interface AuditRow {
  word: Word;
  options: Array<{ word: Word; axes: string[] }>;
  problem?: string;
}

export interface DistractorAuditResult {
  rows: AuditRow[];
  odd: AuditRow[];
  far: AuditRow[];
  short: AuditRow[];
  shortShare: number;
  passed: boolean;
}

const isName = (w: Word) => w.tags.includes('name') || w.tags.includes('proper-noun');

export function auditedWords(words: readonly Word[]): Word[] {
  return words.filter(
    (w) =>
      !isName(w) &&
      w.pinyinNumeric &&
      (w.source === 'textbook' ||
        w.tags.some((t) => /^textbook:[^:]+$/.test(t)) ||
        (w.source === 'tocfl' && w.level !== null && levelIndex(w.level) <= levelIndex('L1'))),
  );
}

export function beginnerKnown(words: readonly Word[]): Set<string> {
  return new Set(
    words
      .filter(
        (w) =>
          (w.source === 'tocfl' && w.level !== null && levelIndex(w.level) <= levelIndex(AUDIT_LEARNER_LEVEL)) ||
          w.tags.includes('textbook:laixue-1'),
      )
      .map((w) => w.id),
  );
}

export function runDistractorAudit(words: readonly Word[], table?: DistractorTable): DistractorAuditResult {
  const index = new ConfusableIndex(words, table ? { table } : {});
  const preferred = beginnerKnown(words);
  const rows: AuditRow[] = [];
  const odd: AuditRow[] = [];
  const far: AuditRow[] = [];
  const short: AuditRow[] = [];
  for (const w of auditedWords(words)) {
    const picks = index.pickDetailed(w, { seed: AUDIT_SEED, preferred, levelCap: AUDIT_LEVEL_CAP });
    const row: AuditRow = { word: w, options: picks.map((p) => ({ word: p.word, axes: [...p.axes] })) };
    const oddWhy = picks.length > 0 ? oddOneOutReason(w, picks.map((p) => p.word)) : undefined;
    // close on an axis, checked again here (a table suggestion counts as a meaning neighbour)
    const suggested = new Set((table?.words[w.id] ?? []).filter(([, a]) => a.includes('suggest')).map(([id]) => id));
    const notClose = picks.filter((p) => axesBetween(w, p.word, charSimilarity).size === 0 && !suggested.has(p.word.id));
    if (oddWhy) {
      row.problem = `odd one out: ${oddWhy}`;
      odd.push(row);
    } else if (notClose.length > 0) {
      row.problem = `not close: ${notClose.map((p) => p.word.headword).join(', ')}`;
      far.push(row);
    }
    if (picks.length < 2) short.push(row);
    rows.push(row);
  }
  const shortShare = rows.length ? short.length / rows.length : 0;
  return { rows, odd, far, short, shortShare, passed: odd.length === 0 && far.length === 0 && shortShare <= MAX_SHORT_SHARE };
}

const fmt = (r: AuditRow) =>
  `| ${r.word.headword} | ${r.word.level ?? ''} | ${r.options.map((o) => `${o.word.headword} (${o.axes.join('+')})`).join(' · ') || '(none: Recall)'} | ${r.problem ?? ''} |`;

export function renderDistractorAudit(res: DistractorAuditResult, extra: AuditRow[] = []): string {
  const by = (k: number) => res.rows.filter((r) => r.options.length === k).length;
  const worst = [...res.odd, ...res.far, ...res.short.filter((r) => !r.problem), ...res.rows.filter((r) => r.options.length === 2 && !r.problem)].slice(0, 50);
  return [
    '# Distractor audit (Phase 48)',
    '',
    'Generated by `pnpm audit:distractors` (CI). Review "Pick the Mandarin" options for every TOCFL N1–L1 word and every',
    `textbook word, seed \`${AUDIT_SEED}\`, an A1 beginner who knows TOCFL N1–L1 and book 1 (level ${AUDIT_LEARNER_LEVEL}, unknown`,
    `options up to ${AUDIT_LEVEL_CAP} or the word's own level). The rule is in \`docs/distractors.md\`.`,
    '',
    `**${res.passed ? 'Passed' : 'FAILED'}.** Words: ${res.rows.length}. Odd one out: ${res.odd.length}. An option not close to the answer: ${res.far.length}. ` +
      `Fewer than 3 options (shown as Recall): ${res.short.length} (${(res.shortShare * 100).toFixed(1)}%, limit ${MAX_SHORT_SHARE * 100}%).`,
    '',
    `Options per word: 4 options ${by(3)}, 3 options ${by(2)}, Recall ${res.short.length}.`,
    '',
    ...(extra.length ? ['## The owner’s words', '', '| word | level | options (axes) | problem |', '|---|---|---|---|', ...extra.map(fmt), ''] : []),
    '## Worst 50',
    '',
    'Failures first, then words with too few close options for a Pick (they show Recall), then 3-option sets.',
    '',
    '| word | level | options (axes) | problem |',
    '|---|---|---|---|',
    ...worst.map(fmt),
    '',
  ].join('\n');
}
